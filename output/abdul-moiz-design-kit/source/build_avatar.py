parts=[]
def finish(o,name,mat,bone='Chest',smooth=True):
    o.name=name
    if mat: o.data.materials.append(mat)
    if o.type=='MESH' and smooth:
        for p in o.data.polygons:p.use_smooth=True
    o['bind_bone']=bone
    parts.append(o)
    return o
def sphere(name,loc,scale,mat,bone='Head',segments=32,rings=20):
    bpy.ops.mesh.primitive_uv_sphere_add(segments=segments,ring_count=rings,location=loc)
    o=bpy.context.object;o.scale=scale
    bpy.ops.object.transform_apply(location=False,rotation=False,scale=True)
    return finish(o,name,mat,bone)
def mesh(name,verts,faces,mat,bone='Head',sub=0):
    d=bpy.data.meshes.new(name);d.from_pydata(verts,[],faces);d.update()
    o=bpy.data.objects.new(name,d);bpy.context.collection.objects.link(o)
    finish(o,name,mat,bone)
    if sub:
        mod=o.modifiers.new('Soft sculpt subdivision','SUBSURF');mod.levels=sub;mod.render_levels=sub
    return o
def curve(name,pts,radius,mat,bone='Head',closed=False,res=3):
    d=bpy.data.curves.new(name,'CURVE');d.dimensions='3D';d.resolution_u=res
    d.bevel_depth=radius;d.bevel_resolution=3
    s=d.splines.new('BEZIER');s.bezier_points.add(len(pts)-1)
    for b,p in zip(s.bezier_points,pts):
        b.co=p[:3];b.handle_left_type='AUTO';b.handle_right_type='AUTO'
        if len(p)>3:b.radius=p[3]
    s.use_cyclic_u=closed
    o=bpy.data.objects.new(name,d);bpy.context.collection.objects.link(o)
    return finish(o,name,mat,bone)
def loft(name,rows,mat,bone='Chest',n=64,sub=1):
    vs=[]
    for z,rx,ry,yoff in rows:
        for i in range(n):
            a=2*math.pi*i/n
            vs.append((rx*math.cos(a),yoff+ry*math.sin(a),z))
    fs=[]
    for j in range(len(rows)-1):
        for i in range(n):a=j*n+i;b=j*n+(i+1)%n;fs.append((a,b,b+n,a+n))
    fs.append(tuple(range(n-1,-1,-1)));fs.append(tuple((len(rows)-1)*n+i for i in range(n)))
    return mesh(name,vs,fs,mat,bone,sub)
def capsule(name,a,b,radii,mat,bone='Chest'):
    a,b=Vector(a),Vector(b);o=sphere(name,(a+b)*.5,(*radii,(b-a).length*.62),mat,bone)
    o.rotation_mode='QUATERNION';o.rotation_quaternion=(b-a).to_track_quat('Z','Y')
    return o

