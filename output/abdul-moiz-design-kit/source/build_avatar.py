def lin(v):
    return v/12.92 if v <= .04045 else ((v+.055)/1.055)**2.4
def rgb(h):
    h=h.lstrip('#'); return tuple(lin(int(h[i:i+2],16)/255) for i in (0,2,4))
def material(name, color, rough=.45, metal=0.0, subsurface=0.0):
    m=bpy.data.materials.new(name); m.use_nodes=True
    p=m.node_tree.nodes.get('Principled BSDF')
    p.inputs['Base Color'].default_value=(*rgb(color),1)
    p.inputs['Roughness'].default_value=rough
    p.inputs['Metallic'].default_value=metal
    p.inputs['Subsurface Weight'].default_value=subsurface
    m.diffuse_color=(*rgb(color),1)
    return m

